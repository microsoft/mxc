const { mkdirSync, readFileSync, writeFileSync } = require("fs");
const { dirname, join } = require("path");

const defaultRepoRoot = join(__dirname, "..", "..");

function contractVariant(version) {
  const match = /^(\d+)\.(\d+)\.(\d+)-([A-Za-z]+)$/.exec(version);
  if (!match) {
    throw new Error(
      `schemas/schema-version.json: cannot map contract version "${version}" to a Rust enum variant`
    );
  }
  const [, major, minor, patch, qualifier] = match;
  const qualifierName = qualifier[0].toUpperCase() + qualifier.slice(1).toLowerCase();
  return `V${major}_${minor}_${patch}${qualifierName}`;
}

const header = `// Copyright (c) Microsoft Corporation.
// Licensed under the MIT License.
//
// @generated by scripts/versioning/generate-schema-version-metadata.js.
// Do not edit by hand.
`;

function generatedOutputs(repoRoot, versions) {
  return new Map([
    [
      join(repoRoot, "src", "core", "wxc_common", "src", "schema_versions.rs"),
      `${header}
use crate::models::ContainmentBackend;
use mxc_config_contract::ContractVersion;

pub fn state_aware_contract(backend: &ContainmentBackend) -> Option<ContractVersion> {
    match backend {
        ContainmentBackend::IsolationSession => Some(ContractVersion::${contractVariant(versions.stateAware)}),
        ContainmentBackend::WindowsSandbox => Some(ContractVersion::${contractVariant(versions.stateAwareWindowsSandbox)}),
        ContainmentBackend::Wslc => Some(ContractVersion::${contractVariant(versions.stateAwareWslc)}),
        ContainmentBackend::ProcessContainer
        | ContainmentBackend::Lxc
        | ContainmentBackend::Vm
        | ContainmentBackend::MicroVm
        | ContainmentBackend::Hyperlight
        | ContainmentBackend::Seatbelt
        | ContainmentBackend::Bubblewrap => None,
    }
}
`,
    ],
    [
      join(repoRoot, "sdk", "node", "src", "generated", "schema-versions.ts"),
      `${header}
export const MIN_VERSION = '${versions.min}' as const;
export const MAX_SUPPORTED_VERSION = '${versions.maxSupported}' as const;
export const LATEST_STABLE_VERSION = '${versions.stableLatest}' as const;
export const STATE_AWARE_VERSION = '${versions.stateAware}' as const;
export const WINDOWS_SANDBOX_STATE_AWARE_VERSION = '${versions.stateAwareWindowsSandbox}' as const;
export const WSLC_STATE_AWARE_VERSION = '${versions.stateAwareWslc}' as const;
`,
    ],
    [
      join(
        repoRoot,
        "sdk",
        "dotnet",
        "Microsoft.Mxc.Sdk",
        "Generated",
        "SchemaVersionMetadata.cs"
      ),
      `${header}
namespace Microsoft.Mxc.Sdk;

internal static class GeneratedSchemaVersions
{
    internal const string Minimum = "${versions.min}";
    internal const string MaximumSupported = "${versions.maxSupported}";
    internal const string LatestStable = "${versions.stableLatest}";
    internal const string StateAware = "${versions.stateAware}";
    internal const string WindowsSandboxStateAware = "${versions.stateAwareWindowsSandbox}";
    internal const string WslcStateAware = "${versions.stateAwareWslc}";
}
`,
    ],
  ]);
}

function run({
  repoRoot = defaultRepoRoot,
  args = process.argv.slice(2),
  stdout = console.log,
  stderr = console.error,
} = {}) {
  const checkOnly = args.includes("--check");
  const unexpectedArgs = args.filter(arg => arg !== "--check");
  if (unexpectedArgs.length > 0) {
    stderr(`Unknown argument(s): ${unexpectedArgs.join(", ")}`);
    return 2;
  }

  let versions;
  try {
    const canonicalPath = join(repoRoot, "schemas", "schema-version.json");
    versions = JSON.parse(readFileSync(canonicalPath, "utf8"));
    for (const key of [
      "min",
      "maxSupported",
      "stateAware",
      "stateAwareWindowsSandbox",
      "stateAwareWslc",
      "stableLatest",
    ]) {
      if (typeof versions[key] !== "string" || versions[key].length === 0) {
        throw new Error(
          `schemas/schema-version.json: ${key} must be a non-empty string`
        );
      }
    }
  } catch (error) {
    stderr(error.message);
    return 1;
  }

  let outputs;
  try {
    outputs = generatedOutputs(repoRoot, versions);
  } catch (error) {
    stderr(error.message);
    return 1;
  }

  let drifted = false;
  for (const [path, content] of outputs) {
    const normalized = content.replace(/\r\n/g, "\n");
    if (checkOnly) {
      let existing;
      try {
        existing = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
      } catch {
        stderr(`Missing generated schema-version metadata: ${path}`);
        drifted = true;
        continue;
      }
      if (existing !== normalized) {
        stderr(`Generated schema-version metadata is stale: ${path}`);
        drifted = true;
      }
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, normalized, "utf8");
      stdout(`wrote ${path}`);
    }
  }

  if (drifted) {
    stderr(
      "Run node scripts/versioning/generate-schema-version-metadata.js and commit the results."
    );
    return 1;
  }

  if (checkOnly) {
    stdout("Generated schema-version metadata is current.");
  }
  return 0;
}

module.exports = { contractVariant, generatedOutputs, run };

if (require.main === module) {
  process.exitCode = run();
}
