<#
.SYNOPSIS
    Regenerates the FlatBuffers Rust bindings for the sandbox_spec crate.

.DESCRIPTION
    Runs `flatc` against external/windows-sdk/base_container/ProcessSecurityEnvironment.fbs,
    preserving the legacy base_container_layout module and replacing only the
    process_security_environment_layout module. Can be run from any directory.

.PARAMETER Flatc
    Path to flatc.exe. Defaults to "flatc.exe" (must be on PATH).

.EXAMPLE
    pwsh -File <repo-path>/src/core/generated/base_container_specification/regenerate.ps1
#>
[CmdletBinding()]
param(
    [string]$Flatc = "flatc.exe"
)

$ErrorActionPreference = 'Stop'

# Resolve repo root from the script location, so the caller does not need to be in the repo.
$repoRoot = (& git -C $PSScriptRoot rev-parse --show-toplevel) 2>$null
if (-not $repoRoot) {
    throw "Could not find the repository root from $PSScriptRoot."
}

# Derive the crate dir from the script's own location so it never goes stale if the crate moves.
$crateDir = $PSScriptRoot
$srcDir   = Join-Path $crateDir "src"
$fbs      = Join-Path $repoRoot "external/windows-sdk/base_container/ProcessSecurityEnvironment.fbs"
$generatedLayoutDir = Join-Path $crateDir ".process_security_environment_layout.$([guid]::NewGuid().ToString('N'))"
$generatedModuleDir = Join-Path $generatedLayoutDir "process_security_environment_layout"
$sourceLayoutDir = Join-Path $srcDir "process_security_environment_layout"

if (-not (Test-Path $fbs)) {
    throw "FlatBuffers schema not found: $fbs"
}
if (-not (Get-Command $Flatc -ErrorAction SilentlyContinue)) {
    throw "flatc not found: $Flatc. Download from https://github.com/google/flatbuffers/releases"
}

# Require flatc >= 25.12.19. Older versions emit elided lifetimes that trigger
# the `mismatched_lifetime_syntaxes` lint (added in Rust 1.89). Fixed upstream
# in flatbuffers PR #8709, first released in v25.12.19.
$minFlatcVersion = [version]'25.12.19'
$versionOutput = (& $Flatc --version) 2>&1 | Out-String
$match = [regex]::Match($versionOutput, 'flatc version (\d+\.\d+\.\d+)')
if (-not $match.Success) {
    throw "Could not parse flatc version from output: $versionOutput"
}
$flatcVersion = [version]$match.Groups[1].Value
if ($flatcVersion -lt $minFlatcVersion) {
    throw "flatc version $flatcVersion is too old. Minimum required: $minFlatcVersion. Download a newer build from https://github.com/google/flatbuffers/releases"
}
Write-Host "Using flatc version $flatcVersion" -ForegroundColor Cyan

Write-Host "Running flatc..." -ForegroundColor Cyan
New-Item -ItemType Directory -Path $generatedLayoutDir -Force | Out-Null
& $Flatc `
    --rust --gen-object-api --force-empty --no-prefix --rust-module-root-file --gen-all `
    -o $generatedLayoutDir `
    $fbs
if ($LASTEXITCODE -ne 0) {
    Remove-Item $generatedLayoutDir -Recurse -Force -ErrorAction SilentlyContinue
    throw "flatc failed with exit code $LASTEXITCODE"
}

$modRs = Join-Path $generatedLayoutDir "mod.rs"
$libRs = Join-Path $srcDir "lib.rs"
if (-not (Test-Path $modRs) -or -not (Test-Path $generatedModuleDir)) {
    Remove-Item $generatedLayoutDir -Recurse -Force -ErrorAction SilentlyContinue
    throw "flatc did not generate the expected module output under $generatedLayoutDir"
}
$libRsContent = Get-Content $libRs -Raw
$modRsContent = Get-Content $modRs -Raw

# Replace the previous generated module on reruns instead of appending duplicates.
$existingModulePattern = '(?ms)\r?\n// Automatically generated by the Flatbuffers compiler\. Do not modify\.\r?\n// @generated\r?\n(?:#!\[[^\r\n]*\]\r?\n)?(?:#\[[^\r\n]*\]\r?\n)?pub mod process_security_environment_layout \{.*?\r?\n\} // process_security_environment_layout\r?\n'
$libRsContent = [regex]::Replace($libRsContent, $existingModulePattern, "`n")

$pattern = '(\} // sandbox_tech_spec_layout)'
$matches = [regex]::Matches($libRsContent, $pattern)
if ($matches.Count -ne 1) {
    throw "Expected exactly one legacy sandbox_tech_spec_layout marker in $libRs, found $($matches.Count)."
}
$modulePattern = '(?m)^pub mod process_security_environment_layout \{'
$moduleMatches = [regex]::Matches($modRsContent, $modulePattern)
if ($moduleMatches.Count -ne 1) {
    throw "Expected exactly one process_security_environment_layout module declaration in $modRs"
}
$modRsContent = [regex]::Replace(
    $modRsContent,
    $modulePattern,
    "#[allow(unused_imports, non_snake_case, non_camel_case_types, clippy::all)]`npub mod process_security_environment_layout {")
$replacement = "`$1`n`n$modRsContent"
$newLibRsContent = [regex]::Replace($libRsContent, $pattern, $replacement)

try {
    Write-Host "Installing generated files..." -ForegroundColor Cyan
    if (Test-Path $sourceLayoutDir) {
        Remove-Item $sourceLayoutDir -Recurse -Force
    }
    Move-Item $generatedModuleDir $sourceLayoutDir
    Set-Content $libRs $newLibRsContent

    Write-Host "Formatting with cargo fmt..." -ForegroundColor Cyan
    Push-Location $srcDir
    try {
        & cargo fmt -p sandbox_spec
        if ($LASTEXITCODE -ne 0) { throw "cargo fmt failed with exit code $LASTEXITCODE" }
    } finally {
        Pop-Location
    }
} finally {
    if (Test-Path $generatedLayoutDir) {
        Remove-Item $generatedLayoutDir -Recurse -Force
    }
}

Write-Host "Done. Regenerated bindings in $srcDir" -ForegroundColor Green
